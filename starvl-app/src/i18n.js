export const LangContext = createContext();

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('pbi_lang') || 'pt-BR');

  function t(key, ...args) {
    const val = (T[lang] ?? T['pt-BR'])[key] ?? T['pt-BR'][key] ?? key;
    return typeof val === 'function' ? val(...args) : val;
  }

  function applyLang(newLang) {
    setLang(newLang);
    localStorage.setItem('pbi_lang', newLang);
  }

  return (
    <LangContext.Provider value={{ lang, t, applyLang }}>
      {children}
    </LangContext.Provider>
  );
}

export function useT() {
  return useContext(LangContext);
}
